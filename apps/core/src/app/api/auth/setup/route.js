import { NextResponse } from 'next/server'
import { writeFile } from 'fs/promises'
import { join } from 'path'

export async function POST(request) {
  try {
    const { username, password } = await request.json()

    // Only allow setup in development
    if (process.env.NODE_ENV !== 'development') {
      return NextResponse.json(
        {
          error: 'Setup not allowed in production',
          message: 'Please configure ADMIN_USERNAME and ADMIN_PASSWORD environment variables in your deployment platform',
          isProduction: true
        },
        { status: 403 }
      )
    }

    // Validate inputs
    if (!username || username.length < 3) {
      return NextResponse.json(
        { error: 'Username must be at least 3 characters' },
        { status: 400 }
      )
    }

    if (!password || password.length < 6) {
      return NextResponse.json(
        { error: 'Password must be at least 6 characters' },
        { status: 400 }
      )
    }

    // Update .env.local file
    const envPath = join(process.cwd(), '.env.local')
    let envContent = ''

    try {
      const { readFile } = await import('fs/promises')
      envContent = await readFile(envPath, 'utf-8')
    } catch (err) {
      // File doesn't exist, create new content
      envContent = `# Admin Credentials\n# Generated by Practice Admin Setup\n# Last updated: ${new Date().toISOString()}\n\n`
    }

    // Update or add credentials
    const lines = envContent.split('\n')
    let usernameFound = false
    let passwordFound = false

    const updatedLines = lines.map(line => {
      if (line.startsWith('ADMIN_USERNAME=')) {
        usernameFound = true
        return `ADMIN_USERNAME=${username}`
      }
      if (line.startsWith('ADMIN_PASSWORD=')) {
        passwordFound = true
        return `ADMIN_PASSWORD=${password}`
      }
      return line
    })

    // Add if not found
    if (!usernameFound) {
      updatedLines.push(`ADMIN_USERNAME=${username}`)
    }
    if (!passwordFound) {
      updatedLines.push(`ADMIN_PASSWORD=${password}`)
    }

    // Update timestamp comment
    const finalContent = updatedLines.join('\n').replace(
      /# Last updated: .*/,
      `# Last updated: ${new Date().toISOString()}`
    )

    await writeFile(envPath, finalContent, 'utf-8')

    return NextResponse.json({
      success: true,
      message: 'Admin credentials saved to .env.local'
    })
  } catch (error) {
    console.error('Setup error:', error)
    return NextResponse.json(
      { error: 'Setup failed: ' + error.message },
      { status: 500 }
    )
  }
}
