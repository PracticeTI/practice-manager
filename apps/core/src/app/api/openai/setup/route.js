import { NextResponse } from 'next/server'
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { setSystemStateValue } from '@/lib/systemState'
import { FALLBACK_OPENAI_MODEL } from '@/lib/openaiModel'

// Only AI provider configuration may be written by this endpoint. It used to
// merge arbitrary client-supplied keys into .env.local.
const ALLOWED_AI_ENV_KEYS = new Set([
  'AI_PROVIDER',
  'AI_MODEL',
  'OPENAI_API_KEY',
  'OPENAI_MODEL',
  'OPENAI_BASE_URL',
  'CLAUDE_API_KEY',
  'ANTHROPIC_API_KEY',
  'CLAUDE_MODEL',
  'GEMINI_API_KEY',
  'GOOGLE_GENERATIVE_AI_API_KEY',
  'GEMINI_MODEL',
  'DEEPSEEK_API_KEY',
  'DEEPSEEK_MODEL',
])

/**
 * Save OpenAI API configuration to .env.local
 * POST /api/openai/setup
 */
export async function POST(request) {
  try {
    const payload = await request.json().catch(() => ({}))
    const envVars = payload?.envVars
    const adminTokenFromBody = typeof payload?.adminToken === 'string' ? payload.adminToken.trim() : ''
    const authHeader = request.headers.get('authorization') || ''
    const adminTokenFromHeader = authHeader.startsWith('Bearer ')
      ? authHeader.slice('Bearer '.length).trim()
      : ''
    const adminToken = adminTokenFromBody || adminTokenFromHeader

    if (!adminToken) {
      return NextResponse.json({ error: 'Unauthorized: missing admin session token. Please log in again.' }, { status: 401 })
    }

    if (!envVars || typeof envVars !== 'object') {
      return NextResponse.json({ error: 'Invalid environment variables' }, { status: 400 })
    }

    const sanitizedEnvVars = Object.fromEntries(
      Object.entries(envVars).filter(([key]) => ALLOWED_AI_ENV_KEYS.has(key))
    )
    if (Object.keys(sanitizedEnvVars).length === 0) {
      return NextResponse.json({ error: 'No supported AI provider variables supplied' }, { status: 400 })
    }

    const incomingApiKey = typeof envVars.OPENAI_API_KEY === 'string' ? envVars.OPENAI_API_KEY.trim() : ''
    const existingApiKey = typeof process.env.OPENAI_API_KEY === 'string' ? process.env.OPENAI_API_KEY.trim() : ''
    const hasAnyApiKey = Boolean(incomingApiKey || existingApiKey)

    const incomingModel = typeof envVars.OPENAI_MODEL === 'string' ? envVars.OPENAI_MODEL.trim() : ''
    const existingModel = typeof process.env.OPENAI_MODEL === 'string' ? process.env.OPENAI_MODEL.trim() : ''
    if (!incomingModel && !existingModel) {
      sanitizedEnvVars.OPENAI_MODEL = FALLBACK_OPENAI_MODEL
    }
    const modelToPersist = incomingModel || existingModel || FALLBACK_OPENAI_MODEL

    // Allow model-only saves; key can be configured later.
    if (!hasAnyApiKey) {
      await setSystemStateValue('openai_model', modelToPersist).catch(() => false)
      return NextResponse.json({
        success: true,
        isProduction: false,
        message: 'OpenAI model saved. Add OPENAI_API_KEY to enable API calls.',
        modelOnly: true,
        model: modelToPersist
      })
    }

    const isVercel = process.env.VERCEL === '1'
    const isProduction = process.env.NODE_ENV === 'production'

    if (isVercel || isProduction) {
      await setSystemStateValue('openai_model', modelToPersist).catch(() => false)
      return NextResponse.json({
        success: false,
        isProduction: true,
        platform: isVercel ? 'vercel' : 'production',
        message: 'Cannot save to .env.local in production environment',
        instructions: {
          vercel: [
            'Go to your Vercel dashboard',
            'Select your project',
            'Go to Settings > Environment Variables',
            'Add OPENAI_API_KEY',
            'Redeploy your application'
          ],
          general: [
            'Add OPENAI_API_KEY to your hosting platform\'s settings',
            'Redeploy your application for changes to take effect'
          ]
        },
        envVars: sanitizedEnvVars
      })
    }

    const envPath = join(process.cwd(), '.env.local')
    let existingContent = ''
    try {
      if (existsSync(envPath)) {
        existingContent = readFileSync(envPath, 'utf-8')
      }
    } catch (readError) {
      console.error('Error reading existing .env.local:', readError)
      // Continue with empty content if file doesn't exist
    }

    const existingVars = {}
    existingContent.split('\n').forEach(line => {
      const trimmed = line.trim()
      if (trimmed && !trimmed.startsWith('#')) {
        const [key, ...valueParts] = trimmed.split('=')
        if (key) {
          existingVars[key.trim()] = valueParts.join('=')
        }
      }
    })

    const mergedVars = { ...existingVars, ...sanitizedEnvVars }

    const lines = [
      '# OpenAI Configuration',
      '# Generated by Practice Admin',
      `# Last updated: ${new Date().toISOString()}`,
      ''
    ]

    Object.entries(mergedVars).forEach(([key, value]) => {
      if (value !== undefined && value !== null) {
        lines.push(`${key}=${value}`)
      }
    })

    const newContent = lines.join('\n') + '\n'

    writeFileSync(envPath, newContent, 'utf-8')

    await setSystemStateValue('openai_model', modelToPersist).catch(() => false)

    return NextResponse.json({
      success: true,
      isProduction: false,
      message: 'OpenAI configuration saved to .env.local',
      note: 'Please restart your backend server for changes to take effect',
      envPath
    })
  } catch (error) {
    console.error('Error saving OpenAI configuration:', error)
    const errorMessage = error instanceof Error ? error.message : String(error)
    return NextResponse.json(
      { error: 'Failed to save configuration: ' + errorMessage },
      { status: 500 }
    )
  }
}
