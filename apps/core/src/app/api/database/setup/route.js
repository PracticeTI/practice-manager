import { NextResponse } from 'next/server'
import { writeFileSync, readFileSync, existsSync } from 'fs'
import { join } from 'path'
import { requireAdminAuth, requireOperatorAuth } from '@/lib/operatorRouteAuth'

/**
 * Save database configuration to .env.local
 * POST /api/database/setup
 */
export async function POST(request) {
    const auth = await requireOperatorAuth(request)
    if (auth.response) return auth.response
  try {
    const { envVars } = await request.json()

    if (!envVars || typeof envVars !== 'object') {
      return NextResponse.json(
        { error: 'Invalid environment variables' },
        { status: 400 }
      )
    }

    // Check if running on Vercel or other hosting platform
    const isVercel = process.env.VERCEL === '1'
    const isProduction = process.env.NODE_ENV === 'production'

    if (isVercel || isProduction) {
      // On Vercel/production, we can't write to filesystem
      // Return instructions for setting environment variables through the platform
      return NextResponse.json({
        success: false,
        isProduction: true,
        platform: isVercel ? 'vercel' : 'production',
        message: 'Cannot save to .env.local in production environment',
        instructions: {
          vercel: [
            'Go to your Vercel dashboard',
            'Select your project',
            'Go to Settings > Environment Variables',
            'Add each variable for Production, Preview, and Development environments',
            'Redeploy your application'
          ],
          general: [
            'Add these environment variables to your hosting platform\'s settings',
            'Redeploy your application for changes to take effect'
          ]
        },
        envVars
      })
    }

    // Path to .env.local in the backend root
    const envPath = join(process.cwd(), '.env.local')

    // Read existing .env.local if it exists
    let existingContent = ''
    if (existsSync(envPath)) {
      existingContent = readFileSync(envPath, 'utf-8')
    }

    // Parse existing variables
    const existingVars = {}
    existingContent.split('\n').forEach(line => {
      const trimmed = line.trim()
      if (trimmed && !trimmed.startsWith('#')) {
        const [key, ...valueParts] = trimmed.split('=')
        if (key) {
          existingVars[key.trim()] = valueParts.join('=')
        }
      }
    })

    // Merge new variables with existing ones
    const mergedVars = { ...existingVars, ...envVars }

    // Generate new .env.local content
    const lines = [
      '# Database Configuration',
      '# Generated by Practice Admin',
      `# Last updated: ${new Date().toISOString()}`,
      '',
    ]

    // Add all variables
    Object.entries(mergedVars).forEach(([key, value]) => {
      if (value !== undefined && value !== null) {
        lines.push(`${key}=${value}`)
      }
    })

    const newContent = lines.join('\n') + '\n'

    // Write to file
    writeFileSync(envPath, newContent, 'utf-8')

    return NextResponse.json({
      success: true,
      isProduction: false,
      message: 'Database configuration saved to .env.local',
      note: 'Please restart the practice server for changes to take effect',
      path: '.env.local'
    })

  } catch (error) {
    console.error('Error saving database configuration:', error)
    return NextResponse.json(
      { error: 'Failed to save configuration', details: error.message },
      { status: 500 }
    )
  }
}
