#!/usr/bin/env node
/**
 * Mount or unmount the private domain overlay.
 *
 * The public release of this app contains no private customer domains. They live in a
 * separate private repository, checked out as a git submodule at `src/private`. That
 * repository exposes an `overlay/` tree whose directories mirror this project's layout:
 *
 *   overlay/app/...        -> src/app/...            (Next.js routes)
 *   overlay/components/... -> src/components/...
 *   overlay/lib/...        -> src/lib/...
 *   overlay/admin-ui/...   -> src/admin-ui/...
 *   overlay/test/...       -> test/...
 *   overlay/scripts/...    -> scripts/...
 *   overlay/public/...     -> public/...
 *   overlay/docs/...       -> docs/...
 *   overlay/content/...    -> content/...           (report templates)
 *
 * Copied paths are recorded in `.private-overlay.json` and excluded through the
 * checkout-local `.git/info/exclude` (written by this script), so the public `.gitignore`
 * never names a private domain. Two generated modules bridge the
 * overlay into the public code:
 *
 *   src/lib/privateDomains.js          - domain descriptors (server/edge safe)
 *   src/components/privateLandings.jsx - client landing components, keyed by domain
 *   tailwind.private.cjs               - theme extensions read by tailwind.config.cjs
 *
 * Usage:
 *   node scripts/sync-private-overlay.mjs           # mount (no-op when the submodule is absent)
 *   node scripts/sync-private-overlay.mjs --clean   # unmount, leaving a pristine public tree
 *   node scripts/sync-private-overlay.mjs --check   # exit 1 if the public tree has private drift
 *
 * Where the overlay comes from, highest precedence first:
 *
 *   1. `PRIVATE_OVERLAY_DIR`   - explicit path to an overlay tree (mounted volume, CI checkout)
 *   2. `src/private/overlay`   - the git submodule
 *   3. a shallow clone of the private repository, when `PRIVATE_OVERLAY_REPO_URL` (or the
 *      `.gitmodules` URL) and a token are both set
 *
 * Hosted builds that cannot check out the submodule must set `PRIVATE_OVERLAY_REQUIRED=1`
 * as well: without it, a build with no overlay silently emits empty stubs, and every
 * customer hostname then falls back to the default domain's branding.
 */

import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

import { DEST_ROOTS, NON_COPIED_DIRS } from './private-overlay-paths.mjs'
import { clearExcludeBlock, writeExcludeBlock } from './private-overlay-excludes.mjs'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const submoduleOverlayRoot = path.join(repoRoot, 'src/private/overlay')
const checkoutRoot = path.join(repoRoot, '.private-overlay-src')
const checkoutOverlayRoot = path.join(checkoutRoot, 'overlay')
const manifestPath = path.join(repoRoot, '.private-overlay.json')
const registryPath = path.join(repoRoot, 'src/lib/privateDomains.js')
const landingsPath = path.join(repoRoot, 'src/components/privateLandings.jsx')
const tailwindThemePath = path.join(repoRoot, 'tailwind.private.cjs')
const tailwindSourcesPath = path.join(repoRoot, 'src/app/private-overlay-sources.css')

/** Source roots Tailwind should scan beyond its own `@source`-driven detection. */
const CSS_SOURCE_DIR = path.join(repoRoot, 'src/app')

/** Extensions whose files can carry class names; everything else is not worth scanning. */
const SCANNABLE_EXTENSIONS = new Set(['.js', '.jsx', '.mjs', '.ts', '.tsx', '.mdx'])

/** Destination roots that can hold markup; overlay docs, scripts and assets never do. */
const SCANNABLE_DEST_ROOTS = ['src/app/', 'src/components/', 'src/lib/', 'src/admin-ui/']

const GENERATED_HEADER = `// AUTO-GENERATED by scripts/sync-private-overlay.mjs - do not edit.
// Regenerate with \`npm run private:sync\` (mounts src/private) or \`npm run private:clean\`.
`

const EMPTY_REGISTRY = `${GENERATED_HEADER}
export const PRIVATE_DOMAINS = []
export const PRIVATE_PUBLIC_API_ROUTES = []
`

const EMPTY_LANDINGS = `${GENERATED_HEADER}
'use client'

export const PRIVATE_LANDING_COMPONENTS = {}
`

const EMPTY_TAILWIND_THEME = `${GENERATED_HEADER}
module.exports = {}
`

const CSS_GENERATED_HEADER = `/* AUTO-GENERATED by scripts/sync-private-overlay.mjs - do not edit.
   Regenerate with \`npm run private:sync\` (mounts src/private) or \`npm run private:clean\`.
   Imported by src/app/globals.css. */
`

const EMPTY_TAILWIND_SOURCES = `${CSS_GENERATED_HEADER}
/* No overlay mounted: Tailwind's automatic source detection covers the public tree. */
`

const args = new Set(process.argv.slice(2))
const cleanMode = args.has('--clean')
const checkMode = args.has('--check')

function log(message) {
  process.stdout.write(`[private-overlay] ${message}\n`)
}

function fail(message) {
  process.stderr.write(`[private-overlay] ${message}\n`)
  process.exit(1)
}

/** True when the caller demands a real overlay instead of the empty public stubs. */
function overlayIsRequired() {
  const raw = String(process.env.PRIVATE_OVERLAY_REQUIRED || '').trim().toLowerCase()
  return raw === '1' || raw === 'true' || raw === 'yes'
}

/** The submodule URL declared for `src/private` in .gitmodules. */
function readSubmoduleUrl() {
  let contents = ''
  try {
    contents = fs.readFileSync(path.join(repoRoot, '.gitmodules'), 'utf8')
  } catch {
    return ''
  }

  for (const block of contents.split(/^\s*\[submodule/m).slice(1)) {
    const declaredPath = block.match(/^\s*path\s*=\s*(.+)$/m)
    if (!declaredPath || declaredPath[1].trim() !== 'src/private') continue
    const declaredUrl = block.match(/^\s*url\s*=\s*(.+)$/m)
    return declaredUrl ? declaredUrl[1].trim() : ''
  }

  return ''
}

function readOverlayToken() {
  for (const name of ['PRIVATE_OVERLAY_TOKEN', 'GITHUB_TOKEN', 'GH_TOKEN']) {
    const value = String(process.env[name] || '').trim()
    if (value) return value
  }
  return ''
}

/**
 * Clone the private repository into `.private-overlay-src` so a hosted build without
 * submodule support can still mount every customer domain.
 */
function checkoutOverlayRepository(remoteUrl, token) {
  const ref = String(process.env.PRIVATE_OVERLAY_REF || '').trim()
  const authorization = `Basic ${Buffer.from(`x-access-token:${token}`).toString('base64')}`
  const cloneArgs = ['clone', '--depth', '1', '--quiet']
  if (ref) cloneArgs.push('--branch', ref)
  cloneArgs.push(remoteUrl, checkoutRoot)

  fs.rmSync(checkoutRoot, { recursive: true, force: true })

  try {
    execFileSync('git', cloneArgs, {
      stdio: ['ignore', 'ignore', 'pipe'],
      // Keeps the token out of the command line (and therefore out of build logs).
      env: {
        ...process.env,
        GIT_CONFIG_COUNT: '1',
        GIT_CONFIG_KEY_0: 'http.https://github.com/.extraheader',
        GIT_CONFIG_VALUE_0: `Authorization: ${authorization}`,
        GIT_TERMINAL_PROMPT: '0',
      },
    })
  } catch (error) {
    const detail = String(error?.stderr || error?.message || '').trim().split('\n')[0]
    fail(`could not clone the private overlay repository${detail ? `: ${detail}` : ''}`)
  }

  log(`checked out the private overlay into ${path.relative(repoRoot, checkoutRoot)}`)
}

/**
 * Locate the overlay tree, or return null when none of the sources are available.
 * @returns {string|null}
 */
function resolveOverlayRoot() {
  const explicitDir = String(process.env.PRIVATE_OVERLAY_DIR || '').trim()
  if (explicitDir) {
    const resolved = path.resolve(repoRoot, explicitDir)
    if (!fs.existsSync(resolved)) {
      fail(`PRIVATE_OVERLAY_DIR points at ${resolved}, which does not exist`)
    }
    log(`using overlay from PRIVATE_OVERLAY_DIR (${path.relative(repoRoot, resolved) || '.'})`)
    return resolved
  }

  if (fs.existsSync(submoduleOverlayRoot)) return submoduleOverlayRoot

  const remoteUrl = String(process.env.PRIVATE_OVERLAY_REPO_URL || '').trim() || readSubmoduleUrl()
  const token = readOverlayToken()
  if (remoteUrl && token) {
    checkoutOverlayRepository(remoteUrl, token)
    if (!fs.existsSync(checkoutOverlayRoot)) {
      fail('the private overlay repository does not contain an overlay/ directory')
    }
    return checkoutOverlayRoot
  }

  return null
}

function readManifest() {
  try {
    const parsed = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
    return Array.isArray(parsed?.files) ? parsed.files : []
  } catch {
    return []
  }
}

function removePreviousOverlay() {
  const previous = readManifest()
  let removed = 0

  for (const relativePath of previous) {
    const absolutePath = path.join(repoRoot, relativePath)
    if (!fs.existsSync(absolutePath)) continue
    fs.rmSync(absolutePath, { force: true })
    removed += 1
  }

  // Prune directories the overlay created and left empty.
  const directories = new Set(previous.map((relativePath) => path.dirname(relativePath)))
  const sorted = [...directories].sort((a, b) => b.length - a.length)
  for (const relativeDir of sorted) {
    let current = path.join(repoRoot, relativeDir)
    while (current.startsWith(repoRoot) && current !== repoRoot) {
      if (!fs.existsSync(current) || fs.readdirSync(current).length > 0) break
      fs.rmdirSync(current)
      current = path.dirname(current)
    }
  }

  fs.rmSync(manifestPath, { force: true })
  return removed
}

function listFiles(root) {
  const results = []
  if (!fs.existsSync(root)) return results

  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      if (entry.name === '.DS_Store' || entry.name === '.git') continue
      const absolute = path.join(current, entry.name)
      if (entry.isDirectory()) walk(absolute)
      else if (entry.isFile()) results.push(absolute)
    }
  }

  walk(root)
  return results
}

function writeGenerated(filePath, contents, written) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, contents)
  written.push(path.relative(repoRoot, filePath))
}

function buildLandingsModule(landings) {
  const entries = Object.entries(landings).filter(([, specifier]) => typeof specifier === 'string' && specifier)
  if (entries.length === 0) return EMPTY_LANDINGS

  const map = entries
    .map(([key, specifier]) => `  ${JSON.stringify(key)}: () => import('${specifier}'),`)
    .join('\n')

  return `${GENERATED_HEADER}
'use client'

/** Lazily loaded landing components, keyed by domain mode. */
export const PRIVATE_LANDING_COMPONENTS = {
${map}
}
`
}

function readLandingsManifest(overlayRoot) {
  const manifest = path.join(overlayRoot, 'lib/landings.json')
  if (!fs.existsSync(manifest)) return {}

  try {
    const parsed = JSON.parse(fs.readFileSync(manifest, 'utf8'))
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {}
  } catch (error) {
    throw new Error(`Could not parse ${path.relative(repoRoot, manifest)}: ${error.message}`)
  }
}

/**
 * Theme extensions an overlay contributes to `tailwind.config.cjs`.
 *
 * The overlay ships `tailwind/theme.json` holding static `theme.extend` values
 * (usually brand colours). Inlining them into one generated module lets the config
 * `require` a stable path instead of reaching into the overlay at build time, and a
 * build with no overlay gets `{}` so the public tree carries no customer palette.
 */
function buildTailwindThemeModule(overlayRoot) {
  const themeJson = path.join(overlayRoot, 'tailwind/theme.json')
  if (!fs.existsSync(themeJson)) return EMPTY_TAILWIND_THEME

  let parsed
  try {
    parsed = JSON.parse(fs.readFileSync(themeJson, 'utf8'))
  } catch (error) {
    throw new Error(`Could not parse ${path.relative(repoRoot, themeJson)}: ${error.message}`)
  }

  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return EMPTY_TAILWIND_THEME

  return `${GENERATED_HEADER}
module.exports = ${JSON.stringify(parsed, null, 2)}
`
}

/**
 * `@source` directives for the mounted overlay.
 *
 * Tailwind v4's automatic source detection skips paths excluded by the checkout's ignore
 * rules, and the overlay is copied only into excluded destinations. Its markup was therefore
 * scanned solely through the overlay's own tree, which a hosted build may not have (a shallow
 * clone, a mounted directory), and customer pages shipped without their utilities.
 * Explicit `@source` paths are not filtered by the ignore rules. They are registered per
 * file rather than per directory because registering a directory only reaches excluded
 * children when that directory is excluded itself.
 */
function buildTailwindSources(destinations) {
  const specifiers = destinations
    .filter((destination) => SCANNABLE_DEST_ROOTS.some((root) => destination.startsWith(root)))
    .filter((destination) => SCANNABLE_EXTENSIONS.has(path.extname(destination)))
    .map((destination) => {
      const relative = path.relative(CSS_SOURCE_DIR, path.join(repoRoot, destination)).split(path.sep).join('/')
      return relative.startsWith('..') ? relative : `./${relative}`
    })

  const unique = [...new Set(specifiers)].sort()
  if (unique.length === 0) return EMPTY_TAILWIND_SOURCES

  return `${CSS_GENERATED_HEADER}${unique.map((specifier) => `@source "${specifier}";\n`).join('')}`
}

function mount(overlayRoot) {
  const written = []
  const sources = fs.readdirSync(overlayRoot, { withFileTypes: true }).filter((entry) => entry.isDirectory())

  for (const entry of sources) {
    if (NON_COPIED_DIRS.has(entry.name)) continue
    const destinationRoot = DEST_ROOTS[entry.name]
    if (!destinationRoot) {
      log(`skipping unknown overlay directory "${entry.name}"`)
      continue
    }

    const sourceRoot = path.join(overlayRoot, entry.name)
    const targetRoot = path.join(repoRoot, destinationRoot)

    for (const sourceFile of listFiles(sourceRoot)) {
      const relative = path.relative(sourceRoot, sourceFile)
      const target = path.join(targetRoot, relative)
      fs.mkdirSync(path.dirname(target), { recursive: true })
      fs.copyFileSync(sourceFile, target)
      written.push(path.relative(repoRoot, target))
    }
  }

  // Tailwind sources are derived from the copied files only, before the generated bridges below
  // join the list.
  const copied = [...written]

  writeGenerated(
    registryPath,
    `${GENERATED_HEADER}
import * as privateDomainData from './privateDomains.data.js'

export const PRIVATE_DOMAINS = Array.isArray(privateDomainData.PRIVATE_DOMAINS)
  ? privateDomainData.PRIVATE_DOMAINS
  : []

/** \`/api\` routes the overlay ships and declares public. Absent from older overlay checkouts. */
export const PRIVATE_PUBLIC_API_ROUTES = Array.isArray(privateDomainData.PRIVATE_PUBLIC_API_ROUTES)
  ? privateDomainData.PRIVATE_PUBLIC_API_ROUTES
  : []
`,
    written
  )
  writeGenerated(landingsPath, buildLandingsModule(readLandingsManifest(overlayRoot)), written)
  writeGenerated(tailwindThemePath, buildTailwindThemeModule(overlayRoot), written)
  writeGenerated(tailwindSourcesPath, buildTailwindSources(copied), written)

  fs.writeFileSync(manifestPath, `${JSON.stringify({ files: written }, null, 2)}\n`)
  writeExcludeBlock(repoRoot, written)
  log(`mounted ${written.length} overlay files from ${path.relative(repoRoot, overlayRoot)}`)
}

if (checkMode) {
  const drift = readManifest()
  const descriptorPath = path.join(repoRoot, 'src/lib/privateDomains.data.js')
  if (fs.existsSync(descriptorPath)) drift.push('src/lib/privateDomains.data.js')
  if (fs.existsSync(checkoutRoot)) drift.push('.private-overlay-src')

  if (drift.length > 0) {
    log(`public tree contains private overlay files:\n  ${drift.join('\n  ')}`)
    log('run `npm run private:clean` before publishing')
    process.exit(1)
  }

  log('public tree is clean')
  process.exit(0)
}

removePreviousOverlay()

if (cleanMode) {
  fs.rmSync(checkoutRoot, { recursive: true, force: true })
  writeGenerated(registryPath, EMPTY_REGISTRY, [])
  writeGenerated(landingsPath, EMPTY_LANDINGS, [])
  writeGenerated(tailwindThemePath, EMPTY_TAILWIND_THEME, [])
  writeGenerated(tailwindSourcesPath, EMPTY_TAILWIND_SOURCES, [])
  clearExcludeBlock(repoRoot)
  log('unmounted the private overlay')
  process.exit(0)
}

const overlayRoot = resolveOverlayRoot()

if (!overlayRoot) {
  if (overlayIsRequired()) {
    fail([
      'no private overlay available and PRIVATE_OVERLAY_REQUIRED is set.',
      'This build would ship the default domain branding to every customer hostname.',
      'Provide one of:',
      '  - src/private (the git submodule: `git submodule update --init --recursive`)',
      '  - PRIVATE_OVERLAY_DIR pointing at an overlay tree',
      '  - PRIVATE_OVERLAY_REPO_URL plus PRIVATE_OVERLAY_TOKEN so the build can clone it',
      'Set PRIVATE_OVERLAY_REQUIRED=0 to allow a public build without customer domains.',
    ].join('\n  '))
  }

  writeGenerated(registryPath, EMPTY_REGISTRY, [])
  writeGenerated(landingsPath, EMPTY_LANDINGS, [])
  writeGenerated(tailwindThemePath, EMPTY_TAILWIND_THEME, [])
  writeGenerated(tailwindSourcesPath, EMPTY_TAILWIND_SOURCES, [])
  clearExcludeBlock(repoRoot)
  log('no private submodule present - generated empty domain registry')
  process.exit(0)
}

mount(overlayRoot)
